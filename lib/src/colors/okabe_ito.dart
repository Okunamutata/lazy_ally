import 'package:flutter/material.dart';

import 'package:lazy_ally/src/colors/contrast.dart';

/// Individual hues from the Okabe-Ito palette — colors chosen to remain
/// distinguishable under the common forms of color vision deficiency
/// (protanopia, deuteranopia, tritanopia). Named directly rather than
/// indexed into a shared list, which is easy to misalign.
///
/// Source: Okabe, M. & Ito, K. (2008), "Color Universal Design (CUD)".
const Color _okabeItoOrange = Color(0xFFE69F00);
const Color _okabeItoSkyBlue = Color(0xFF56B4E9);
const Color _okabeItoBluishGreen = Color(0xFF009E73);
const Color _okabeItoVermillion = Color(0xFFD55E00);

/// Full Okabe-Ito-based [ColorScheme]s — one per [Brightness] — used as
/// `LazyAllyController`'s default `colorBlindScheme` when a consumer doesn't
/// supply their own.
///
/// [ColorScheme.primary]/[ColorScheme.secondary]/[ColorScheme.tertiary]/
/// [ColorScheme.error] are pinned to four maximally-distinguishable
/// Okabe-Ito hues, each with its own correctly contrasted `onX` color
/// computed from that hue directly (not inherited from the seed, which
/// would be wrong for the overridden hues). Every other slot — surfaces,
/// containers, outlines — is generated by [ColorScheme.fromSeed], so it
/// keeps Material 3's own contrast guarantees rather than being hand-picked
/// here.
final ColorScheme kOkabeItoColorSchemeLight = _okabeItoScheme(Brightness.light);

/// Dark counterpart of [kOkabeItoColorSchemeLight].
final ColorScheme kOkabeItoColorSchemeDark = _okabeItoScheme(Brightness.dark);

ColorScheme _okabeItoScheme(Brightness brightness) {
  return ColorScheme.fromSeed(
    seedColor: _okabeItoOrange,
    brightness: brightness,
    primary: _okabeItoOrange,
    onPrimary: lazyAllyOnColorFor(_okabeItoOrange),
    secondary: _okabeItoSkyBlue,
    onSecondary: lazyAllyOnColorFor(_okabeItoSkyBlue),
    tertiary: _okabeItoBluishGreen,
    onTertiary: lazyAllyOnColorFor(_okabeItoBluishGreen),
    error: _okabeItoVermillion,
    onError: lazyAllyOnColorFor(_okabeItoVermillion),
  );
}
