import 'package:flutter/material.dart';

import 'package:lazy_ally/src/colors/contrast.dart';

/// Individual hues from the IBM color-blind-safe palette — colors chosen to
/// remain distinguishable under the common forms of color vision deficiency
/// (protanopia, deuteranopia, tritanopia). Named directly rather than
/// indexed into a shared list, which is easy to misalign.
///
/// Source: IBM Design Language, "Color blindness"
/// (https://www.ibm.com/design/language/color/#color-blindness).
const Color _ibmColorBlindUltramarine = Color(0xFF648FFF);
const Color _ibmColorBlindGold = Color(0xFFFFB000);
const Color _ibmColorBlindOrange = Color(0xFFFE6100);
const Color _ibmColorBlindMagenta = Color(0xFFDC267F);

/// Full IBM-color-blind-based [ColorScheme]s — one per [Brightness] — used
/// as `LazyAllyController`'s default `colorBlindScheme` when a consumer
/// doesn't supply their own.
///
/// [ColorScheme.primary]/[ColorScheme.secondary]/[ColorScheme.tertiary]/
/// [ColorScheme.error] are pinned to four maximally-distinguishable IBM
/// color-blind-safe hues, each with its own correctly contrasted `onX`
/// color computed from that hue directly (not inherited from the seed,
/// which would be wrong for the overridden hues). Every other slot —
/// surfaces, containers, outlines — is generated by [ColorScheme.fromSeed],
/// so it keeps Material 3's own contrast guarantees rather than being
/// hand-picked here.
final ColorScheme kIbmColorBlindSchemeLight =
    _ibmColorBlindScheme(Brightness.light);

/// Dark counterpart of [kIbmColorBlindSchemeLight].
final ColorScheme kIbmColorBlindSchemeDark =
    _ibmColorBlindScheme(Brightness.dark);

ColorScheme _ibmColorBlindScheme(Brightness brightness) {
  return ColorScheme.fromSeed(
    seedColor: _ibmColorBlindUltramarine,
    brightness: brightness,
    primary: _ibmColorBlindUltramarine,
    onPrimary: lazyAllyOnColorFor(_ibmColorBlindUltramarine),
    secondary: _ibmColorBlindGold,
    onSecondary: lazyAllyOnColorFor(_ibmColorBlindGold),
    tertiary: _ibmColorBlindOrange,
    onTertiary: lazyAllyOnColorFor(_ibmColorBlindOrange),
    error: _ibmColorBlindMagenta,
    onError: lazyAllyOnColorFor(_ibmColorBlindMagenta),
  );
}
