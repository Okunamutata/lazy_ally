import 'package:flutter/material.dart';

import 'package:lazy_ally/src/colors/contrast.dart';

/// Individual hues from the IBM color-blind-safe palette. These colors stay
/// distinguishable under the common forms of color vision deficiency:
/// protanopia, deuteranopia, and tritanopia. Each hue has its own name
/// instead of an index into a shared list, because an index is easy to
/// misalign.
///
/// Source: IBM Design Language, "Color blindness"
/// (https://www.ibm.com/design/language/color/#color-blindness).
const Color _ibmColorBlindUltramarine = Color(0xFF648FFF);
const Color _ibmColorBlindGold = Color(0xFFFFB000);
const Color _ibmColorBlindOrange = Color(0xFFFE6100);
const Color _ibmColorBlindMagenta = Color(0xFFDC267F);

/// Full IBM-color-blind-based [ColorScheme]s, one per [Brightness].
/// `LazyAllyController` uses these as its default `colorBlindScheme` when
/// a consumer does not supply its own.
///
/// [ColorScheme.primary], [ColorScheme.secondary], [ColorScheme.tertiary],
/// and [ColorScheme.error] are pinned to four maximally-distinguishable
/// IBM color-blind-safe hues. Each hue has its own correctly contrasted
/// `onX` color, computed directly from that hue rather than inherited from
/// the seed, because the seed value would be wrong for the overridden
/// hues. Every other slot, such as surfaces, containers, and outlines, is
/// generated by [ColorScheme.fromSeed]. This keeps Material 3's own
/// contrast guarantees instead of hand-picked values here.
final ColorScheme kIbmColorBlindSchemeLight = _ibmColorBlindScheme(
  Brightness.light,
);

/// Dark counterpart of [kIbmColorBlindSchemeLight].
final ColorScheme kIbmColorBlindSchemeDark = _ibmColorBlindScheme(
  Brightness.dark,
);

ColorScheme _ibmColorBlindScheme(Brightness brightness) {
  return ColorScheme.fromSeed(
    seedColor: _ibmColorBlindUltramarine,
    brightness: brightness,
    primary: _ibmColorBlindUltramarine,
    onPrimary: lazyAllyOnColorFor(_ibmColorBlindUltramarine),
    secondary: _ibmColorBlindGold,
    onSecondary: lazyAllyOnColorFor(_ibmColorBlindGold),
    tertiary: _ibmColorBlindOrange,
    onTertiary: lazyAllyOnColorFor(_ibmColorBlindOrange),
    error: _ibmColorBlindMagenta,
    onError: lazyAllyOnColorFor(_ibmColorBlindMagenta),
  );
}
